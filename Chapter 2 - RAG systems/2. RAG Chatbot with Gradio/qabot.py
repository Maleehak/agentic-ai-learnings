## LLM
def get_llm():
    # Specify the model and project settings 
    model_id = "llama3.2:1b"

    # Wrap up the model into Olama inference
    olama_llm = ChatOllama(
            model=model_id,
            temperature=0
        )
    
    return olama_llm

## Document loader
def document_loader(file):
    loader = PyPDFLoader(file.name)
    loaded_document = loader.load()
    return loaded_document

## Text splitter
def text_splitter(data):
    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=1000,
        chunk_overlap=50,
        length_function=len,
    )
    chunks = text_splitter.split_documents(data)
    return chunks

## Vector db
def vector_database(chunks):
    embedding_model = ollama_embedding()
    vectordb = Chroma.from_documents(chunks, embedding_model)
    return vectordb

## Embedding model
def ollama_embedding():
    embeddings = OllamaEmbeddings(
        model="nomic-embed-text"
    )
    return embeddings

## Retriever
def retriever(file):
    splits = document_loader(file)
    chunks = text_splitter(splits)
    vectordb = vector_database(chunks)
    retriever = vectordb.as_retriever()
    return retriever

## QA Chain
def retriever_qa(file, query):
    llm = get_llm()
    retriever_obj = retriever(file)
    prompt = ChatPromptTemplate.from_template(
        "Answer the question based only on the following context:\n\n{context}\n\nQuestion: {input}"
    )
    combine_docs_chain = create_stuff_documents_chain(llm, prompt)
    qa = create_retrieval_chain(retriever_obj, combine_docs_chain)
    response = qa.invoke({"input": query})
    return response["answer"]

# Create Gradio interface
rag_application = gr.Interface(
    fn=retriever_qa,
    inputs=[
        gr.File(
            label="Upload PDF File",
            file_count="single",
            file_types=[".pdf"],
            type="filepath"
        ),
        gr.Textbox(
            label="Input Query",
            lines=2,
            placeholder="Type your question here..."
        )
    ],
    outputs=gr.Textbox(label="Output"),
    title="RAG Chatbot",
    description="Upload a PDF document and ask a question."
)

rag_application.launch(
    server_name="127.0.0.1",
    server_port=7860,
    share=False
)
